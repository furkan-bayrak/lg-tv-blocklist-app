#!/usr/bin/env node
/*
 * Generate src/bundle-info.gen.ts from app/appinfo.json and the bundled preset
 * provenance headers. Run before TypeScript compilation; no upstream checkout
 * or network is needed. The date is the source commit date, not build freshness.
 *
 * Usage: node tools/gen-bundle-info.mjs [appDir] [tsOutPath]
 * Defaults: <repo>/app and <repo>/src/bundle-info.gen.ts.
 * Refresh lists first with build-filter-input.mjs, then gen-domains.mjs, using
 * the same checkout. If upstream committed src changes without updated lists,
 * run its scripts/build.py in a disposable checkout of that exact revision
 * before invoking those generators; never modify the owner's sibling checkout.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const appDir = process.argv[2] ? resolve(process.argv[2]) : join(root, 'app');
const outPath = process.argv[3] ? resolve(process.argv[3]) : join(root, 'src', 'bundle-info.gen.ts');

function provenance(tier) {
  const file = join(appDir, 'filter', 'filter-input-' + tier + '.txt');
  const text = readFileSync(file, 'utf8');
  const revision = /^# source: lg-tv-blocklist @ ([0-9a-f]{40})$/m.exec(text);
  const date = /^# source-date: (\d{4}-\d{2}-\d{2})$/m.exec(text);
  if (!revision || !date) {
    throw new Error(file + ': missing bundled source revision/date; regenerate with tools/build-filter-input.mjs');
  }
  return { revision: revision[1], date: date[1] };
}

const appInfo = JSON.parse(readFileSync(join(appDir, 'appinfo.json'), 'utf8'));
if (typeof appInfo.version !== 'string' || !appInfo.version) {
  throw new Error('appinfo.json has no app version');
}
const safe = provenance('safe');
const strict = provenance('strict');
if (safe.revision !== strict.revision || safe.date !== strict.date) {
  throw new Error('SAFE and STRICT bundled source revision/date differ; regenerate together');
}
const text = [
  '/* GENERATED by tools/gen-bundle-info.mjs from appinfo.json and bundled list headers. */',
  'var LgBundleInfo = {',
  '  appVersion: ' + JSON.stringify(appInfo.version) + ',',
  '  listRevision: ' + JSON.stringify(safe.revision) + ',',
  '  listDate: ' + JSON.stringify(safe.date),
  '};',
  ''
].join('\n');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, text, 'utf8');
console.log('bundle-info: app ' + appInfo.version + ', list ' + safe.revision + ' (' + safe.date + ') -> ' + outPath);
